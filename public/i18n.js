  const LANGS = ['en', 'de', 'fr'];

  /** Catering presets per language, used when seeding a new fixture's list. */
  const PRESETS = {
    en: ['Coffee', 'Milk', 'Sugar', 'Tea', 'Fruit', 'Cake', 'Water', 'Soft drinks', 'Cups', 'Napkins'],
    de: ['Kaffee', 'Milch', 'Zucker', 'Tee', 'Obst', 'Kuchen', 'Wasser', 'Softdrinks', 'Becher', 'Servietten'],
    fr: ['Café', 'Lait', 'Sucre', 'Thé', 'Fruits', 'Gâteau', 'Eau', 'Boissons', 'Gobelets', 'Serviettes'],
  };

  let lang = 'en';

  function pickInitial(stored) {
    if (stored && LANGS.includes(stored)) return stored;
    for (const tag of (navigator.languages || [navigator.language || 'en'])) {
      const base = String(tag).toLowerCase().slice(0, 2);
      if (LANGS.includes(base)) return base;
    }
    return 'en';
  }

  function t(key, vars) {
    let out = DICT[lang][key];
    if (out === undefined) out = DICT.en[key];
    if (out === undefined) return key;
    if (!vars) return out;
    return out.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m));
  }

  window.I18N = {
    get lang() { return lang; },
    set(next) { lang = LANGS.includes(next) ? next : 'en'; document.documentElement.lang = lang; return lang; },
    pickInitial,
    langs: LANGS,
    name: (code) => DICT[code]['lang.name'],
    presets: () => PRESETS[lang] || PRESETS.en,
    presetLabel: (name) => {
      const source = String(name).toLowerCase();
      for (const code of LANGS) {
        const index = PRESETS[code].findIndex((preset) => preset.toLowerCase() === source);
        if (index >= 0) return (PRESETS[lang] || PRESETS.en)[index];
      }
      return name;
    },
    t,
  };
